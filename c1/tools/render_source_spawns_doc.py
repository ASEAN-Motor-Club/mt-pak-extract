#!/usr/bin/env python3
"""Render c1_source_spawns_pois.json into the markdown reference doc."""
import hashlib
import json
import os
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else 'c1/source/c1_source_spawns_pois.json'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'c1/docs/C1_SOURCE_SPAWNS_POIS.md'
ZIP = '/opt/data/inbox/c1src/c1_src.zip'

d = json.load(open(SRC))
pois = d['pois']
sha = hashlib.sha256(open(ZIP, 'rb').read()).hexdigest()


def table(rows, header):
    out = ['| ' + ' | '.join(header) + ' |', '|' + '|'.join(['---'] * len(header)) + '|']
    for r in rows:
        out.append('| ' + ' | '.join(str(c) for c in r) + ' |')
    return '\n'.join(out)


def fmt(p):
    return (p['name'], ', '.join(f"{p['bng_m'][0]:.2f}"), )

L = []
A = L.append
A('# C1 source map — spawn points and POIs\n')
A('Derived from the **original BeamNG level** (not from the port), so every number here is '
  'source ground truth rather than a guess about where something "should" go.\n')
A('## Provenance\n')
A(f'- archive: `{ZIP}` ({os.path.getsize(ZIP)} B)')
A(f'- sha256: `{sha}`')
A('- level: `levels/c1` of the BeamNG mod map **C1 Tokyo Expressway Shutokow**')
A(f"- source metadata: {d['map_meta']['title']!r}, authors {d['map_meta']['authors']}, "
  f"size {d['map_meta']['size']} m, biome {d['map_meta']['biome']!r}, "
  f"rightHandDrive={d['map_meta']['roadRules'].get('rightHandDrive')}")
A('- regenerated by `c1/tools/extract_source_spawns_pois.py` — re-run it rather than editing '
  'this file by hand\n')

A('## Coordinate frames\n')
A('| frame | rule |')
A('|---|---|')
A('| `bng_m` | BeamNG level metres. X east, Y north, Z up. Every `position` in the level JSON. |')
A('| `ue_cm` | Motor Town / Unreal: `(x*100, -y*100, z*100)` — metres→cm with **Y negated**. '
  'Matches the level actor transforms (`set_transforms.py`: `loc = (org[0]*100, -org[1]*100, 0)`). |')
A('')
A('Two independent checks that the Y sign is right:')
A('- the shipped port PlayerStart `(169915, -692979, 84352)` cm decodes to source '
  '`(1699.15, 6929.79)` m, which sits **0.0 m** from the authored C1 loop centreline '
  '(`c1_road_points.json`), i.e. exactly on the road;')
A('- `c3_13.obj` bbox is x 1463–1991 m / y 6557–7029 m and that spawn falls inside it.\n')
A('`dist_to_c1_loop_m` is measured to the **shipped** 14 km loop spline; '
  '`dist_to_source_road_m` to the **source\'s own 305 DecalRoad** network. A POI can be on a '
  'real source road and still be outside the port (that is the case for most of them).\n')

A('## Counts\n')
rows = [(k, v) for k, v in sorted(d['counts'].items())]
A(table(rows, ['kind', 'count']))
inc = sum(1 for p in pois if p['in_shipped_corridor'])
A(f'\n{inc} of {len(pois)} POIs fall inside the shipped 74-cell corridor '
  f'({sum(1 for p in pois if p["kind"]=="tunnel_portal" and p["in_shipped_corridor"])} tunnel portals, '
  f'{sum(1 for p in pois if p["kind"]=="speed_trap" and p["in_shipped_corridor"])} speed traps).\n')

A('## Spawn points (the map\'s own spawn menu)\n')
A('From `levels/c1/main/missiongroup/playerdroppoints/items.level.json` + `levels/c1/info.json`.\n')
rows = []
for p in [q for q in pois if q['kind'] == 'spawn']:
    x, y, z = p['bng_m']
    rows.append([p['name'], p.get('source_label') or '', f'{x:.2f}', f'{y:.2f}', f'{z:.2f}',
                 ', '.join(f'{v:.0f}' for v in p['ue_cm']),
                 f"{p['yaw_ue_derived']}" if p.get('yaw_ue_derived') is not None else '—',
                 p['cell'], int(p['in_shipped_corridor']), f"{p['dist_to_c1_loop_m']:.0f}",
                 f"{p['dist_to_source_road_m']:.1f}"])
A(table(rows, ['object', 'label', 'x m', 'y m', 'z m', 'ue cm', 'yaw°', 'cell', 'in port',
               'dist→loop m', 'dist→src road m']))
A('\nNotes:')
A('- `spawn_default` (Shibaura PA) is `defaultSpawnPointName`, i.e. where the map actually drops '
  'a player in freeroam.')
A('- `spawn_garage` is a **placeholder at the origin** (0.39, 0, −0.84 — note the Z is 0): BeamNG '
  'rewrites it to the active garage slot at runtime, so it carries no usable coordinate. Do not '
  'port it as a fixed point.')
A('- `yaw°` is derived (`atan2(-m01, m00)` off the source `rotationMatrix`, sign flipped for the '
  'mirrored Y). Positions are exact; treat yaw as unverified until one is checked in game.')
A('- **None of the six source spawns is inside the shipped 74-cell corridor.** The nearest to the '
  'port\'s own PlayerStart is Shibaura PA at ~2.3 km. The port starts players on a bare road point '
  'at `(1699.15, 6929.79)` m, which corresponds to no source spawn object.\n')

A('## Garages\n')
A('BeamNG marks garage slots with invisible `parkstage_outline` markers plus a `BeamNGTrigger` '
  'entrance (`garage_marker/`, `garage_triggers/`). The facility itself is declared in '
  '`facilities/facilities.facilities.json`: one garage, "Tokyo, Ota City, Workshop", zone '
  '`garagemain` + spot `garage1spot`, whose site coordinates are **prefab-local** '
  '(z ≈ −0.0146) and only resolve through the prefab instance — use the trigger/marker world '
  'positions below.\n')
rows = []
for p in pois:
    if p['kind'] not in ('garage_entrance', 'garage_marker'):
        continue
    x, y, z = p['bng_m']
    rows.append([p['kind'], p['name'], f'{x:.2f}', f'{y:.2f}', f'{z:.2f}',
                 ', '.join(f'{v:.0f}' for v in p['ue_cm']),
                 f"{p.get('yaw_ue_derived')}", p['cell'], f"{p['dist_to_c1_loop_m']:.0f}"])
A(table(rows, ['kind', 'name', 'x m', 'y m', 'z m', 'ue cm', 'yaw°', 'cell', 'dist→loop m']))
A('\nAll four garage sites are **6.5–8.0 km outside** the shipped loop, so they cannot be reused '
  'as-is: `PLAN-garage.md`\'s proposal (one garage at the spawn cell, then one every ~2 km along '
  'the spline) is still the right shape. These coordinates are the reference for what a real '
  'BeamNG garage footprint looks like: two entrances ~8–12 m apart facing the road, entrance '
  'triggers about 4 m above the marker plane.\n')

A('## Parking / garage-to-garage sites\n')
A('`gameplay/missions/c1/garagetogarage/globalinfo/garages.sites.json` (8 spots, the endpoints '
  'the built-in Garage-to-Garage missions use) and `levels/c1/city.sites.json` (3 lots). These are '
  'the strongest POI candidates: each already has a spot count and a rotation.\n')
rows = []
for p in pois:
    if p['kind'] not in ('g2g_garage_site', 'city_parking'):
        continue
    x, y, z = p['bng_m']
    rows.append([p['kind'], p['name'], p.get('spot_amount') or '', f'{x:.2f}', f'{y:.2f}',
                 f'{z:.2f}', ', '.join(f'{v:.0f}' for v in p['ue_cm']), p['cell'],
                 f"{p['dist_to_c1_loop_m']:.0f}"])
A(table(rows, ['kind', 'spot', 'spots', 'x m', 'y m', 'z m', 'ue cm', 'cell', 'dist→loop m']))
A('')

A('## Speed traps\n')
A(f"{sum(1 for p in pois if p['kind']=='speed_trap')} `BeamNGTrigger` speed traps "
  '(`missiongroup/trap/`). The map advertises "Speed traps" as a feature, so these are both a POI '
  'and a gameplay hook. Only the ones inside the corridor are listed; the full set is in the JSON.\n')
rows = []
for p in pois:
    if p['kind'] != 'speed_trap' or not p['in_shipped_corridor']:
        continue
    x, y, z = p['bng_m']
    rows.append([p.get('source_name'), f'{x:.2f}', f'{y:.2f}', f'{z:.2f}',
                 ', '.join(f'{v:.0f}' for v in p['ue_cm']), p['cell'],
                 f"{p['dist_to_c1_loop_m']:.0f}"])
A(table(rows, ['object', 'x m', 'y m', 'z m', 'ue cm', 'cell', 'dist→loop m']))
A('')

A('## Tunnel portals (zone boundaries)\n')
A(f"{sum(1 for p in pois if p['kind']=='tunnel_portal')} `Portal` actors, i.e. tunnel mouths — "
  'each pair is inner/outer bore. 30 are inside the shipped corridor; those are the ones a '
  'player actually drives through.\n')
rows = []
for p in pois:
    if p['kind'] != 'tunnel_portal' or not p['in_shipped_corridor']:
        continue
    x, y, z = p['bng_m']
    rows.append([p['name'], f'{x:.2f}', f'{y:.2f}', f'{z:.2f}',
                 ', '.join(f'{v:.0f}' for v in p['ue_cm']), p['cell'],
                 f"{p['dist_to_c1_loop_m']:.0f}"])
A(table(rows, ['portal', 'x m', 'y m', 'z m', 'ue cm', 'cell', 'dist→loop m']))
A('')

A('## Port equivalents (C1Full)\n')
ref = d['port_reference']
sm = d['port_summary']
A(f"Every POI is mapped into the **shipped full port**: `{ref['pak']}` "
  f"({ref['cells_shipped']} cell meshes). World position is the same transform throughout — "
  f"`{ref['frame']}`.\n")
A('Verified against the ported geometry, not just the arithmetic: for each POI the nearest '
  'vertex of its containing cell mesh is measured in XY and Z (`deck test` = within 25 m XY and '
  '|dz| ≤ 5 m).\n')
A(f"- {sm['pois']} POIs over {sm['cells']} cells")
A(f"- {sm['cell_mesh_shipped']} of {sm['pois']} land in a cell whose mesh **ships in the pak** "
  f"({sm['missing_cell']} missing)")
A(f"- {sm['on_ported_deck']} of {sm['pois']} pass the deck test — ported geometry is physically "
  f"at that XY and height")
A('')
rows = []
import collections
_c = collections.Counter()
_t = collections.Counter()
for p in pois:
    _t[p['kind']] += 1
    _c[p['kind']] += int(p['port']['on_ported_deck'])
for k in sorted(_t):
    rows.append([k, f"{_c[k]}/{_t[k]}"])
A(table(rows, ['kind', 'on ported deck']))
A('\nGaps are vertical, not positional: the misses are stacked decks (parking above the '
  'carriageway), tunnel bores (portal at the mouth, nearest vertex is wall/roof), and the '
  'origin placeholder `spawn_garage`. None of them is a missing cell — every cell ships.\n')

A('### Spawns, in port coordinates\n')
rows = []
for p in pois:
    if p['kind'] != 'spawn':
        continue
    b = p['port']
    rows.append([p['name'], p.get('source_label') or '', ', '.join(f'{v:.0f}' for v in p['ue_cm']),
                 b['port_cell'], int(b['in_full_port']),
                 f"{b.get('mesh_nearest_vertex_m')}", f"{b.get('dz_vs_mesh_m')}",
                 int(b['on_ported_deck'])])
A(table(rows, ['object', 'label', 'port world cm', 'cell', 'cell ships', 'nearest vertex m',
               'dz to mesh m', 'deck']))
A('')

A('### Garages and parking, in port coordinates\n')
rows = []
for p in pois:
    if p['kind'] not in ('garage_entrance', 'garage_marker', 'g2g_garage_site', 'city_parking'):
        continue
    b = p['port']
    rows.append([p['kind'], p['name'], ', '.join(f'{v:.0f}' for v in p['ue_cm']),
                 b['port_cell'], f"{b.get('mesh_nearest_vertex_m')}",
                 f"{b.get('dz_vs_mesh_m')}", int(b['on_ported_deck'])])
A(table(rows, ['kind', 'name', 'port world cm', 'cell', 'nearest vertex m', 'dz to mesh m',
               'deck']))
A('\nCell actor origins (`cell_actor_ue_cm` in the JSON) come from `cell_origins.json`, the build '
  'input `set_transforms.py` consumed — that is `(origin_m*100, -origin_m_y*100, 0)`. Do **not** '
  'compute a local offset from the world-space cell OBJs: their bboxes bleed across the nominal '
  '500 m grid, so `world − origin` is not the asset-local coordinate. Place against the world '
  'position.\n')

A('## What this means for the port\n')
A('- The shipped corridor is a **subset**: 14 km of loop, 74 cells. Source spawns, garages and '
  'most parking are on roads the port does not carry, so "the map has spawns" and "the port has '
  'spawns" are different sets and must not be conflated.')
A('- Inside the corridor the source gives you 36 usable anchors — 30 tunnel portals and 6 speed '
  'traps — and each sits within ~42 m of the shipped loop spline and within ~28 m of a real '
  'source road, so they are directly placeable.')
A('- Mesh/actor transform convention is `(x, -y, z) * 100`; the road-spline authoring JSON is the '
  'opposite (`+y`). Mixing the two silently mirrors half the map — check every new placement '
  'against the loop spline (expect ≤ ~5 m) before committing it.')
A('- For spawns and garages inside the port, do not invent coordinates from this table: pick a '
  'corridor cell, offset laterally off the carriageway, and snap to the cell top surface '
  '(`PLAN-garage.md` procedure). Use the source points here only as the *layout* reference '
  '(pairing, spacing, entrance orientation).')
A('- **On C1Full the substitution problem disappears.** All 144 source POIs land in cells that '
  'ship in the pak, so the source coordinate *is* the placement — no re-siting, no derived '
  'offset. Add spawns/garages at these world positions and the deck test above already tells you '
  'whether the point sits on geometry (`dz ≈ 0`) or on a structure above/below it.')


os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w').write('\n'.join(L) + '\n')
print('wrote', OUT, os.path.getsize(OUT), 'B')
